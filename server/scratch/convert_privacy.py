for p in paragraphs:
    lines = p.strip().split('\n')
    
    if len(lines) == 1 and re.match(r'^[A-Z0-9\.\s\?]+$', lines[0]) and len(lines[0]) > 5:
        # Heading
        if "PRIVACY POLICY" in lines[0]:
            html.append(f'        <h1>{lines[0]}</h1>')
        else:
            html.append(f'        <h2>{lines[0]}</h2>')
    elif lines[0].startswith('In Short:'):
        html.append(f'        <p><strong><em>{lines[0]}</em></strong></p>')
        if len(lines) > 1:
            content = " ".join(lines[1:])
            html.append(f'        <p>{content}</p>')
    elif "•" in p:
        # Contains list
        current_p = []
        in_list = False
        for line in lines:
            line = line.strip()
            if line.startswith('•'):
                if not in_list:
                    if current_p:
                        html.append(f'        <p>{" ".join(current_p)}</p>')
                        current_p = []
                    html.append('        <ul>')
                    in_list = True
                html.append(f'            <li>{line[1:].strip()}</li>')
            elif in_list and not line.startswith('•') and not line.endswith('.'):
                # Continuation of list item
                html[-1] = html[-1][:-5] + " " + line + "</li>"
            else:
                if in_list:
                    html.append('        </ul>')
                    in_list = False
                current_p.append(line)
        if in_list:
            html.append('        </ul>')
        if current_p:
            html.append(f'        <p>{" ".join(current_p)}</p>')
    else:
        # Regular paragraph
        content = " ".join(lines)
        
        # Bold important terms
        content = re.sub(r'([A-Z][a-zA-Z\s]+(?:\.))', r'<strong>\1</strong>', content, count=1) if "Personal Information Provided by You" in content or "Sensitive Information" in content else content
        
